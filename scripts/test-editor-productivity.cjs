// Run against disposable local data, with Playwright supplied by NODE_PATH.
const { strict: assert } = require('node:assert');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const playwright = require('playwright');
const port = process.env.YAVC_CHROME_TEST_PORT || '8412';
if (!/^\d+$/.test(port)) throw new Error('Use a disposable local port.');
const evidence = path.join(os.tmpdir(), 'yavc-editor-productivity'); fs.mkdirSync(evidence, { recursive: true });
async function run(engine) {
    const browser = await playwright[engine].launch(), page = await browser.newPage({ viewport: { width: 1800, height: 1050 } }), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const action = (app, name, input = {}) => page.evaluate(({ app, name, input }) => pudlActions.run('yavc.' + app + '/' + name + '@1', input, { grant: 'all' }), { app, name, input });
    const dg = (name, input) => action('diagrams', name, input);
    const ed = (name, input) => action('editor', name, input);
    const holdWrites = () => page.evaluate(() => {
        window.realWrite = pcSiteFs.write; window.held = []; window.calls = [];
        pcSiteFs.write = (...args) => { calls.push([args[1], args[2]]); return new Promise(resolve => held.push(() => realWrite(...args).then(resolve))); };
    });
    const command = (id, root = '.dg') => page.evaluate(({ id, root }) => pudlCommands.run(id, null, document.querySelector(root)), { id, root });
    const idle = () => page.waitForFunction(() => document.querySelector('.dg-cv-editor') && !document.querySelector('.sc-diagram-stale'));
    const doc = async () => JSON.parse((await dg('diagram')).text);
    const select = items => dg('canvas-view', { op: 'select', items: items.map(id => ({ id, kind: 'node' })) });
    const fill = async (label, value) => { const e = page.getByLabel(label, { exact: true }); await e.fill(value); await e.dispatchEvent('change'); await idle(); };
    let phase = 'Inspector';
    try {
        await page.goto(`http://diagrams.localhost:${port}/`); await page.locator('.cm-editor').waitFor();
        await dg('new', { kind: 'canvas', style: 'flowchart' }); await select(['process']);
        const sizes = await page.getByRole('group', { name: 'Line Style', exact: true }).evaluate(e => ({ group: e.clientWidth, seg: e.querySelector('.seg').getBoundingClientRect().width }));
        assert.ok(sizes.seg < sizes.group - 20, JSON.stringify(sizes));
        await dg('canvas-view', { op: 'select', key: 'start-process', kind: 'edge' });
        const picker = page.locator('.dg-property-picker').first();
        assert.ok(await picker.evaluate(e => e.getBoundingClientRect().width < e.closest('.form-group').clientWidth - 20));
        await page.locator('.dg-inspector').screenshot({ path: path.join(evidence, engine + '-intrinsic-inspector.png') });
        phase = 'Theme Default'; await select([]);
        const background = () => page.locator('.dg-cv-editor').evaluate(e => getComputedStyle(e).backgroundColor);
        const initial = await background();
        await fill('Background', '#123456'); assert.equal(await background(), 'rgb(18, 52, 86)');
        await page.getByRole('button', { name: 'Theme Default', exact: true }).click(); await idle();
        assert.equal((await doc()).yavc.background, undefined); assert.equal(await background(), initial);
        await command('undo'); await idle(); assert.equal(await background(), 'rgb(18, 52, 86)');
        await command('redo'); await idle(); assert.equal(await background(), initial);
        await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; });
        await page.waitForFunction(initial => getComputedStyle(document.querySelector('.dg-cv-editor')).backgroundColor !== initial, initial);
        const dark = await background();
        await fill('Background', '#654321'); await page.getByRole('button', { name: 'Theme Default', exact: true }).click(); await idle();
        assert.equal(await background(), dark); assert.equal((await doc()).yavc.background, undefined);
        phase = 'Outline and arrangement'; await command('toggle-outline');
        const outline = page.getByRole('complementary', { name: 'Canvas Outline', exact: true }); await outline.waitFor();
        await outline.getByRole('button', { name: 'Start', exact: true }).click();
        assert.equal(await outline.getByRole('button', { name: 'Start', exact: true }).getAttribute('aria-pressed'), 'true');
        await outline.getByRole('button', { name: 'Process', exact: true }).click({ modifiers: ['Control'] });
        assert.equal(await outline.locator('[aria-pressed="true"]').count(), 2);
        await outline.getByRole('button', { name: 'Start', exact: true }).focus(); await page.keyboard.press('ArrowDown');
        assert.equal(await outline.getByRole('button', { name: 'Process', exact: true }).evaluate(e => e === document.activeElement), true);
        await page.keyboard.press('F6'); assert.equal(await page.locator('.dg-inspector').evaluate(e => e.contains(document.activeElement)), true);
        await page.keyboard.press('F6'); assert.equal(await page.locator('.cm-editor').evaluate(e => e.contains(document.activeElement)), true);
        await page.keyboard.press('Shift+F6'); assert.equal(await page.locator('.dg-inspector').evaluate(e => e.contains(document.activeElement)), true);
        await page.keyboard.press('Shift+F6'); await page.keyboard.press('Shift+F6');
        assert.equal(await page.locator('.dg-stage').evaluate(e => e === document.activeElement), true);
        await page.locator('.dg-stage').press('ArrowRight'); await idle();
        const source = { nodes: ['a', 'b', 'c'].map((id, i) => ({ id, type: 'text', text: id, x: [0, 120, 400][i], y: i * 100, width: 80, height: 60 })), edges: [] };
        await dg('new', { kind: 'canvas', text: JSON.stringify(source) }); await select(['a', 'b', 'c']);
        await command('cv-align-top'); await idle(); assert.deepEqual((await doc()).nodes.map(n => n.y), [0, 0, 0]);
        await command('undo'); await idle(); assert.deepEqual((await doc()).nodes.map(n => n.y), [0, 100, 200]);
        await select(['a', 'b', 'c']); await command('cv-distribute-horizontal'); await idle(); assert.deepEqual((await doc()).nodes.map(n => n.x), [0, 200, 400]);
        await page.screenshot({ path: path.join(evidence, engine + '-outline-arranged.png') });
        const separator = page.getByRole('separator', { name: 'Resize the Inspector', exact: true });
        const bodyWidth = await page.locator('.dg-body').evaluate(e => e.clientWidth);
        await separator.focus(); for (let i = 0; i < 5; i++) await page.keyboard.press('Shift+ArrowRight'); await page.waitForTimeout(350);
        await select(['a']);
        assert.equal(await page.getByRole('group', { name: 'Horizontal Alignment', exact: true }).locator('button span:not(.glyph)').first().evaluate(e => getComputedStyle(e).display), 'none');
        assert.ok(await page.locator('.dg-inspector').evaluate(e => e.scrollWidth <= e.clientWidth + 1));
        assert.equal(await page.locator('.dg-body').evaluate(e => e.clientWidth), bodyWidth);
        phase = 'Editor delayed save';
        await page.goto(`http://editor.localhost:${port}/`); await page.locator('.cm-editor').waitFor();
        await ed('new', { path: '~/save-race.md', text: 'A' });
        await ed('save');
        await holdWrites();
        await page.evaluate(() => { window.pending = pudlActions.run('yavc.editor/save@1', {}, { grant: 'all' }); });
        await page.waitForFunction(() => held.length === 1); await ed('set-text', { text: 'B' });
        await page.evaluate(async () => { held.shift()(); await pending; });
        assert.equal((await ed('document')).modified, true);
        // Let the original Visual view finish loading its engine before
        // navigation; WebKit reports a cancelled WASM fetch as a page error.
        await page.waitForFunction(() => typeof window.yavcMdEngine === 'function');
        await page.evaluate(() => window.yavcMdEngine().then(() => true));
        await page.reload(); await page.locator('.cm-editor').waitFor({ state: 'attached' });
        await ed('view', { mode: 'text' });
        await page.waitForFunction(() => typeof window.yavcMdEngine === 'function');
        await page.evaluate(() => window.yavcMdEngine().then(() => true));
        assert.equal((await ed('document')).text, 'B'); assert.equal((await ed('document')).modified, true);
        await holdWrites();
        await page.evaluate(() => { window.pending = pudlActions.run('yavc.editor/save@1', {}, { grant: 'all' }); });
        await page.waitForFunction(() => held.length === 1); await ed('set-text', { text: 'C' });
        await page.evaluate(() => { window.pendingTwo = pudlActions.run('yavc.editor/save@1', {}, { grant: 'all' }); });
        assert.equal(await page.evaluate(() => held.length), 1);
        await page.evaluate(async () => { held.shift()(); await pending; }); await page.waitForFunction(() => held.length === 1);
        await page.evaluate(async () => { held.shift()(); await pendingTwo; });
        assert.equal((await ed('document')).modified, false);
        assert.equal(await page.evaluate(() => pcSiteFs.readHome(pcSiteFs.resolve(pcSiteFs.home(), '~/save-race.md'))), 'C');
        phase = 'Editor inactive rename';
        await page.evaluate(() => { window.pending = pudlActions.run('yavc.editor/save@1', { path: '~/renamed.json' }, { grant: 'all' }); });
        await page.waitForFunction(() => held.length === 1); await ed('new', { path: '~/other.txt', text: 'Other' });
        await page.evaluate(async () => { held.shift()(); await pending; });
        assert.equal((await ed('document')).text, 'Other'); assert.equal((await ed('document')).modified, true);
        const documents = await ed('documents'); assert.ok(documents.documents.some(d => d.path === '~/renamed.json'));
        assert.equal(documents.documents.find(d => d.path === '~/renamed.json').lang, 'json');
        assert.equal((await ed('document')).lang, 'text');
        assert.equal(await page.locator('.cm-editor').evaluate(e => CM.EditorView.findFromDOM(e).state.doc.toString()), 'Other');
        phase = 'Editor failure recovery';
        await page.evaluate(() => { pcSiteFs.write = async () => ({ error: 'Synthetic write failure' }); });
        await assert.rejects(() => ed('save'), /Synthetic write failure/); assert.equal((await ed('document')).modified, true);
        await page.evaluate(() => { pcSiteFs.write = realWrite; }); await ed('save'); assert.equal((await ed('document')).modified, false);
        phase = 'Editor closed-instance acknowledgement';
        await ed('set-text', { text: 'Old instance submission' }); await holdWrites();
        await page.evaluate(() => { window.pending = pudlActions.run('yavc.editor/save@1', {}, { grant: 'all' }).then(() => 'saved', e => e.message); });
        await page.waitForFunction(() => held.length === 1);
        await page.evaluate(() => { window.pendingClose = pudlActions.run('yavc.editor/close@1', {}, { grant: 'all' }); });
        await page.getByRole('button', { name: "Don't Save", exact: true }).click(); await page.evaluate(() => pendingClose);
        await ed('open-file', { path: '~/other.txt' }); await ed('set-text', { text: 'Reopened draft' });
        await page.evaluate(async () => { held.shift()(); await pending; pcSiteFs.write = realWrite; });
        assert.equal((await ed('document')).text, 'Reopened draft'); assert.equal((await ed('document')).modified, true);
        await page.reload(); await page.locator('.cm-editor').waitFor({ state: 'attached' });
        assert.ok((await ed('documents')).documents.some(d => d.path === '~/renamed.json'));
        assert.equal((await ed('document')).text, 'Reopened draft');
        assert.deepEqual(errors, []);
        console.log(engine + ': intrinsic Inspector controls, visible theme reset/history, Outline, arrangement, keyboard panes and Editor save ordering/lifecycle passed');
    } catch (err) {
        await page.screenshot({ path: path.join(evidence, engine + '-failure.png') }).catch(() => {}); err.message = phase + ': ' + err.message; throw err;
    } finally { await browser.close(); }
}
(async () => { for (const engine of process.argv.slice(2).length ? process.argv.slice(2) : ['chromium']) await run(engine); })().catch(e => { console.error(e); process.exit(1); });
