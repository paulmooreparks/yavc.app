"""Build the offline paper catalog from a downloaded IANA IPP XML registry."""
import hashlib
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

source = Path(sys.argv[1])
output = Path(__file__).resolve().parent.parent / 'apps/md-editor/paper-sizes.js'
ns = {'i': 'http://www.iana.org/assignments'}
rows = []
special = {
    'na_letter': ('letter', 'Letter (ANSI A)'), 'na_legal': ('legal', 'Legal'),
    'na_ledger': ('tabloid', 'Tabloid / Ledger (ANSI B)'), 'na_executive': ('executive', 'Executive'),
    'na_invoice': ('statement', 'Statement / Half Letter'), 'na_c': ('ansi-c', 'ANSI C'),
    'na_d': ('ansi-d', 'ANSI D'), 'na_e': ('ansi-e', 'ANSI E'),
    'na_govt-letter': ('government-letter', 'Government Letter'), 'na_govt-legal': ('government-legal', 'Government Legal'),
}

registry = ET.parse(source)
for row in registry.findall('.//i:record', ns):
    if row.findtext('i:attribute', '', ns) != 'media' or row.findtext('i:type', '', ns) != 'size name':
        continue
    key = row.findtext('i:value', '', ns)
    m = re.fullmatch(r'([a-z]+)_([a-z0-9-]+)_([0-9.]+)x([0-9.]+)(mm|in)', key)
    if not m:
        continue
    family, name, width, height, unit = m.groups()
    identity = key
    label = name.replace('-', ' ').title()
    if family == 'iso':
        label = name.upper().replace('-EXTRA', ' Extra').replace('-TAB', ' Tab').replace('-LONG-FLAP', ' Long Flap')
        if re.fullmatch(r'[abc][0-9]+', name): identity = name
        group = 'ISO A' if name.startswith(('a', '2a')) else 'ISO B' if name.startswith('b') else 'ISO Envelopes' if name.startswith(('c', 'dl')) else 'ISO Untrimmed and Cards'
    elif family == 'jis':
        label = 'JIS ' + name.upper(); group = 'Japanese'
    elif family == 'jpn':
        group = 'Japanese'
    elif family in ('prc', 'roc'):
        label = family.upper() + ' ' + name.upper(); group = 'Chinese and Taiwanese'
    elif family in ('na', 'asme'):
        group = 'North American'
        if name.startswith('arch-'): label = 'ARCH ' + name[5:].upper(); group = 'Architectural'
        if family == 'asme': label = 'ASME ' + name.upper()
    else:
        group = 'Other Metric' if unit == 'mm' else 'Other Inch Sizes'
    if family + '_' + name in special:
        identity, label = special[family + '_' + name]
    if 'photo' in name: group = 'Photo'
    rows.append({'id': identity, 'pwg': key, 'label': label, 'group': group, 'width': float(width), 'height': float(height), 'unit': unit, 'variant': name.endswith('-long-flap')})

assert len(rows) >= 200 and len({r['id'] for r in rows}) == len(rows)
header = '''/* Copyright 2026 Paul Parks. SPDX-License-Identifier: Apache-2.0 */
/* Generated by scripts/build-paper-sizes.py from IANA IPP media size names.
   Registry data is CC0: https://www.iana.org/help/licensing-terms
   Source: https://www.iana.org/assignments/ipp-registrations/ipp-registrations.xml
   Registry SHA-256: %s
   Registry updated %s. No runtime network access is needed. */
(function () {
    'use strict';
    window.yavcPaperSizes = Object.freeze([
'''
output.write_text(header % (hashlib.sha256(source.read_bytes()).hexdigest(), registry.getroot().findtext('i:updated', '', ns)) + ',\n'.join('        ' + json.dumps(row, ensure_ascii=False, separators=(',', ':')) for row in rows) + '\n    ].map(Object.freeze));\n})();\n', encoding='utf-8', newline='\n')
print(f'Generated {len(rows)} registered paper sizes.')
