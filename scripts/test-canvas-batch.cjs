// Supply Playwright through NODE_PATH. Use disposable localhost data.
const { strict: assert } = require('node:assert');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os');
const playwright = require('playwright');
const port = process.env.YAVC_CHROME_TEST_PORT || '8412';
if (!/^\d+$/.test(port)) throw new Error('Use a disposable local port.');
const evidence = path.join(os.tmpdir(), 'yavc-canvas-batch'); fs.mkdirSync(evidence, { recursive: true });
async function run(engine) {
    const browser = await playwright[engine].launch(), page = await browser.newPage({ viewport: { width: 1800, height: 1050 } }), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const action = (name, input = {}) => page.evaluate(({ name, input }) => pudlActions.run('yavc.diagrams/' + name + '@1', input, { grant: 'all' }), { name, input });
    const command = id => page.evaluate(id => pudlCommands.run(id, null, document.querySelector('.dg')), id);
    const doc = async () => JSON.parse((await action('diagram')).text);
    const idle = () => page.waitForFunction(() => document.querySelector('.dg-cv-editor') && !document.querySelector('.sc-diagram-stale'));
    const select = async key => { await action('canvas-view', { op: 'select', key, kind: 'node' }); await idle(); };
    const setField = async (label, value) => { const field = page.getByLabel(label, { exact: true }); await field.fill(value); await field.dispatchEvent('change'); await idle(); };
    let phase = 'startup';
    try {
        await page.goto(`http://diagrams.localhost:${port}/`); await page.locator('.cm-editor').waitFor();
        phase = 'diagram settings'; await action('new', { kind: 'canvas', style: 'blank' });
        assert.equal(await page.locator('.dg-inspector-title').innerText(), 'Diagram');
        await page.getByLabel('Show Grid', { exact: true }).focus(); await page.keyboard.press('Space'); await idle();
        assert.equal(await page.getByLabel('Show Grid', { exact: true }).evaluate(e => document.activeElement === e), true);
        assert.equal((await doc()).yavc.grid, true); assert.ok(await page.locator('.dg-cv-grid').count());
        await page.getByLabel('Snap to Grid and Shapes', { exact: true }).uncheck(); await idle(); assert.equal((await doc()).yavc.snap, false);
        await setField('Background', '#102030'); assert.equal((await doc()).yavc.background, '#102030');
        assert.equal(await page.locator('.dg-cv-editor').evaluate(e => getComputedStyle(e).backgroundColor), 'rgb(16, 32, 48)');
        assert.equal(await page.locator('.dg-cv-editor > svg').first().evaluate(e => getComputedStyle(e).backgroundColor), 'rgba(0, 0, 0, 0)');
        await page.screenshot({ path: path.join(evidence, engine + '-diagram-settings.png') });
        const free = await action('canvas-edit', { op: 'create', x: 3, y: 5, text: 'Free movement' });
        await action('canvas-view', { op: 'fit' }); await action('canvas-view', { op: 'actual' });
        const freeHit = page.locator('.dg-cv-hit[data-id="' + free.key + '"]'), freeBox = await freeHit.boundingBox();
        await page.mouse.move(freeBox.x + freeBox.width / 2, freeBox.y + freeBox.height / 2); await page.mouse.down();
        await page.mouse.move(freeBox.x + freeBox.width / 2 + 10, freeBox.y + freeBox.height / 2 + 10, { steps: 4 }); await page.mouse.up(); await idle();
        assert.deepEqual((await doc()).nodes.map(n => [n.x, n.y]), [[13, 15]]);
        phase = 'templates and inline text';
        await page.getByRole('menuitem', { name: 'File', exact: true }).click();
        await page.getByRole('menuitem', { name: 'New Canvas', exact: true }).click();
        await page.getByRole('menuitem', { name: 'Flowchart', exact: true }).click(); await idle();
        assert.ok((await doc()).nodes.some(n => n.yavc && n.yavc.shape === 'diamond'));
        await page.locator('.dg-cv-hit[data-id="process"]').dblclick();
        const inline = page.getByLabel('Text (Markdown)', { exact: true }); await inline.waitFor();
        await inline.fill('**Live text**\nSecond line'); await idle();
        assert.equal((await doc()).nodes.find(n => n.id === 'process').text, '**Live text**\nSecond line');
        assert.equal(await inline.evaluate(e => document.activeElement === e), true);
        await page.screenshot({ path: path.join(evidence, engine + '-inline-text.png') });
        await inline.press('Control+z'); await idle(); assert.equal((await doc()).nodes.find(n => n.id === 'process').text, 'Process');
        await inline.press('Control+Shift+z'); await idle(); assert.match((await doc()).nodes.find(n => n.id === 'process').text, /Live text/);
        await inline.press('Escape'); assert.equal(await inline.count(), 0);
        await page.locator('.dg-stage').press('Enter'); await inline.waitFor(); await inline.fill('Saved live text'); await inline.press('Escape'); await idle();
        phase = 'independent colors'; await select('process');
        await setField('Fill Color', '#000000'); await setField('Outline Color', '#ff0000');
        let item = (await doc()).nodes.find(n => n.id === 'process'); assert.equal(item.yavc.fillColor, '#000000'); assert.equal(item.yavc.strokeColor, '#ff0000');
        await page.waitForFunction(() => document.querySelector('g[data-text="process"] .dg-cv-text')?.style.color === 'rgb(255, 255, 255)');
        await page.getByRole('group', { name: 'Fill Color Presets', exact: true }).getByRole('button', { name: 'Default', exact: true }).click(); await idle();
        item = (await doc()).nodes.find(n => n.id === 'process'); assert.equal(item.yavc.fillColor, undefined); assert.equal(item.yavc.strokeColor, '#ff0000');
        phase = 'splitters and folding';
        const width = () => page.locator('.dg-inspector').evaluate(e => e.getBoundingClientRect().width);
        const initialWidth = await width(); assert.ok(initialWidth >= 330, String(initialWidth));
        const outer = page.getByRole('separator', { name: 'Resize the Text', exact: true }); await outer.focus(); await page.keyboard.press('Shift+ArrowRight');
        await page.waitForTimeout(350); assert.ok(Math.abs(await width() - initialWidth) <= 1, 'Outer split changed Inspector width');
        const inner = page.getByRole('separator', { name: 'Resize the Inspector', exact: true }); await inner.focus(); await page.keyboard.press('Shift+ArrowRight');
        // The splitter is still moving when the key press returns. Wait until the Inspector has moved, then until its width has held for several frames.
        await page.waitForFunction(limit => document.querySelector('.dg-inspector').getBoundingClientRect().width < limit, initialWidth - 30);
        const chosen = await page.evaluate(() => new Promise((resolve, reject) => {
            const inspector = document.querySelector('.dg-inspector'), giveUp = setTimeout(() => reject(new Error('The Inspector width did not settle.')), 10000);
            let last = -1, held = 0;
            (function frame() {
                const now = inspector.getBoundingClientRect().width; held = now === last ? held + 1 : 0; last = now;
                if (held >= 5) { clearTimeout(giveUp); resolve(now); } else requestAnimationFrame(frame);
            })();
        }));
        assert.ok(chosen < initialWidth - 30);
        const mediumRows = await page.getByRole('group', { name: 'Horizontal Alignment', exact: true }).getByRole('button').evaluateAll(all => [...new Set(all.map(e => Math.round(e.getBoundingClientRect().top)))].length);
        assert.equal(mediumRows, 2);
        await outer.focus(); await page.keyboard.press('Shift+ArrowLeft'); await page.waitForTimeout(350); assert.ok(Math.abs(await width() - chosen) <= 1);
        await inner.focus(); for (let i = 0; i < 3; i++) await page.keyboard.press('Shift+ArrowRight'); await page.waitForTimeout(350);
        const horizontal = page.getByRole('group', { name: 'Horizontal Alignment', exact: true });
        assert.equal(await horizontal.getByRole('button', { name: 'Default', exact: true }).locator('span:not(.glyph)').evaluate(e => getComputedStyle(e).display), 'none');
        assert.equal(await horizontal.getByRole('button', { name: 'Bottom', exact: true }).count(), 0);
        assert.ok(await horizontal.getByRole('button', { name: 'Right', exact: true }).getAttribute('title'));
        await page.locator('.dg-inspector').screenshot({ path: path.join(evidence, engine + '-narrow-inspector.png') });
        await inner.press('Enter'); await page.waitForTimeout(350);
        phase = 'delayed saves'; await action('save', { path: '~/batch.canvas' });
        await page.evaluate(() => {
            const adapter = pudlHost.contentResourceAdapter;
            window.originalWrite = adapter.write; window.originalCreate = adapter.create;
            window.heldWrites = [];
            adapter.write = request => new Promise((resolve, reject) => heldWrites.push(() => originalWrite(request).then(resolve, reject)));
            adapter.create = request => new Promise((resolve, reject) => heldWrites.push(() => originalCreate(request).then(resolve, reject)));
            window.pendingSave = pudlActions.run('yavc.diagrams/save@1', {}, { grant: 'all' });
        });
        await page.waitForFunction(() => heldWrites.length > 0);
        await select('process'); await page.locator('.dg-stage').press('Enter'); await inline.fill('Newer than saved text'); await inline.press('Escape'); await idle();
        await page.evaluate(async () => { heldWrites.shift()(); await pendingSave; });
        assert.equal((await action('diagram')).modified, true);
        assert.doesNotMatch(await page.evaluate(() => pudlHost.fs.readText('~/batch.canvas')), /Newer than saved text/);
        await page.evaluate(() => { window.pendingSave = pudlCommands.run('save', null, document.querySelector('.dg')); });
        await page.waitForFunction(() => heldWrites.length > 0);
        await action('new', { kind: 'canvas', style: 'sequence' });
        const sequence = await doc(); assert.ok(sequence.nodes.some(n => n.id === 'client-lane'));
        const before = (await action('diagram')).text;
        await page.evaluate(async () => { heldWrites.shift()(); await pendingSave; }); assert.equal((await action('diagram')).text, before);
        assert.equal(await page.locator('[data-role="where"]').innerText(), 'Not saved yet');
        await page.screenshot({ path: path.join(evidence, engine + '-sequence.png') });
        phase = 'save ordering';
        // Both explicit action saves are queued for the same resource. The
        // second write cannot start until the first actually completes.
        await action('set-text', { text: before.replace('Client', 'Version A') });
        await page.evaluate(() => { window.firstSave = pudlActions.run('yavc.diagrams/save@1', { path: '~/ordered.canvas' }, { grant: 'all' }); });
        await page.waitForFunction(() => heldWrites.length === 1);
        await action('set-text', { text: before.replace('Client', 'Version B') });
        await page.evaluate(() => { window.secondSave = pudlActions.run('yavc.diagrams/save@1', { path: '~/ordered.canvas' }, { grant: 'all' }); });
        await action('set-text', { text: before.replace('Client', 'Version A') });
        assert.equal(await page.evaluate(() => heldWrites.length), 1);
        await page.evaluate(async () => { heldWrites.shift()(); await firstSave; });
        await page.waitForFunction(() => heldWrites.length === 1);
        await page.evaluate(async () => { heldWrites.shift()(); await secondSave; });
        assert.match(await page.evaluate(() => pudlHost.fs.readText('~/ordered.canvas')), /Version B/);
        assert.equal((await action('diagram')).modified, true);
        phase = 'inactive Save As and recovery';
        await page.evaluate(() => {
            window.oldPathSave = pudlCommands.run('save', null, document.querySelector('.dg'));
        });
        await page.waitForFunction(() => heldWrites.length === 1);
        await action('set-text', { text: before.replace('Client', 'Version B') });
        await page.evaluate(() => {
            window.originalSaveAs = pudlHost.contentResourceAdapter.saveAs;
            pudlHost.contentResourceAdapter.saveAs = (request, context) => new Promise(resolve => { window.saveAsRequest = request; window.saveAsContext = context; window.releaseSaveAs = resolve; });
            window.pendingSaveAs = pudlCommands.run('save-as', null, document.querySelector('.dg'));
        });
        await action('set-text', { text: before.replace('Client', 'Version A') });
        assert.equal(await page.evaluate(() => typeof window.releaseSaveAs), 'undefined');
        await page.evaluate(async () => { heldWrites.shift()(); await oldPathSave; pudlHost.contentResourceAdapter.write = originalWrite; pudlHost.contentResourceAdapter.create = originalCreate; });
        await page.waitForFunction(() => !!window.releaseSaveAs);
        await action('new', { kind: 'canvas', style: 'blank' });
        const newNode = await action('canvas-edit', { op: 'create', text: 'Recover Me', x: 0, y: 0 });
        assert.match(await page.evaluate(() => saveAsContext.checkName('wrong.d2')), /extension/);
        assert.equal(await page.evaluate(() => saveAsContext.checkName('sequence-copy.canvas')), null);
        await page.evaluate(async () => { releaseSaveAs(await originalCreate({resource:'~/sequence-copy.canvas',text:saveAsRequest.text})); await pendingSaveAs; pudlHost.contentResourceAdapter.saveAs = originalSaveAs; });
        assert.match(await page.evaluate(() => pudlHost.fs.readText('~/sequence-copy.canvas')), /Version B/);
        assert.equal((await action('diagrams')).diagrams.find(d => d.path === '~/sequence-copy.canvas').modified, true);
        assert.equal(await page.locator('.dg').getAttribute('data-kind'), 'canvas');
        assert.equal(await page.locator('[data-role="where"]').innerText(), 'Not saved yet');
        await select(newNode.key); await page.locator('.dg-stage').press('Enter'); await inline.fill('Recovered inline edit'); await idle();
        await page.waitForFunction(() => Object.values(sessionStorage).some(v => v.includes('sequence-copy')));
        await page.reload(); await page.locator('.cm-editor').waitFor(); await idle();
        assert.equal((await doc()).nodes[0].text, 'Recovered inline edit');
        assert.ok((await action('diagrams')).diagrams.some(d => d.path === '~/sequence-copy.canvas' && d.kind === 'canvas'));
        phase = 'close prompt';
        const closing = action('close'); await page.getByRole('button', { name: 'Cancel', exact: true }).click(); await closing;
        assert.equal((await doc()).nodes[0].text, 'Recovered inline edit');
        assert.deepEqual(errors, []);
        console.log(engine + ': combined Canvas settings, templates, inline text/history, colors, fixed Inspector, folding and delayed saves passed');
    } catch (err) {
        await page.screenshot({ path: path.join(evidence, engine + '-failure.png') });
        console.error(engine + ' failed during ' + phase + ': ' + JSON.stringify(errors)); throw err;
    } finally { await browser.close(); }
}
(async () => { for (const engine of process.argv.slice(2).length ? process.argv.slice(2) : ['chromium']) await run(engine); })().catch(e => { console.error(e); process.exitCode = 1; });
